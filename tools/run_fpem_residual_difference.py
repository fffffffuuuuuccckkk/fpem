def ordered_loader(dataset, args, ids, batch_size=None):
    wrapped = IndexedDataset(dataset, cycle_len=args.cyclenet_cycle_len)
    return DataLoader(Subset(wrapped, list(ids)), batch_size=batch_size or args.batch_size,
                      shuffle=False, num_workers=0)


def shuffled_loader(dataset, args, ids, seed):
    wrapped = IndexedDataset(dataset, cycle_len=args.cyclenet_cycle_len)
    generator = torch.Generator().manual_seed(seed)
    return DataLoader(Subset(wrapped, list(ids)), batch_size=args.batch_size,
                      shuffle=True, generator=generator, num_workers=0)


def fresh_a0(args, device, seed):
    torch.manual_seed(seed)
    cfg = model_config(args, "A0")
    try:
        return Model(cfg).to(device)
    except ValueError as exc:
        if args.backbone != "moderntcn" or "predictive_env_backbone" not in str(exc):
            raise
        from models.PatchTST_PredictiveEnvIV_shared import Model as ModernModel
        return ModernModel(cfg).to(device)


def train_fold_reference(args, dataset, device, seed, last_source_id, epochs,
                         checkpoint, max_batches=0):
    model = fresh_a0(args, device, seed)
    if checkpoint.exists():
        saved = torch.load(checkpoint, map_location=device, weights_only=False)
        if saved["last_source_id"] != last_source_id or saved["epochs"] != epochs:
            raise ValueError("OOF fold reference checkpoint configuration mismatch")
        model.load_state_dict(saved["state"])
    else:
        optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)
        for epoch in range(epochs):
            model.train()
            train = shuffled_loader(dataset, args, range(last_source_id + 1), seed + epoch)
            for batch_index, (x, y, _, cycle) in enumerate(train):
                if max_batches and batch_index >= max_batches:
                    break
                x = x.float().to(device)
                y = y[:, -args.pred_len:].float().to(device)
                output = model.forward_components(x, cycle.to(device))["prediction"]
                loss = F.mse_loss(output, y)
                if not torch.isfinite(loss):
                    raise FloatingPointError("fold A0 loss is non-finite")
                optimizer.zero_grad(set_to_none=True)
                loss.backward()
                optimizer.step()
            print(json.dumps({"fold_reference_epoch": epoch + 1,
                              "last_source_id": last_source_id,
                              "last_batch_loss": float(loss.detach())}), flush=True)
        model.initialize_h_forecast_head()
        checkpoint.parent.mkdir(parents=True, exist_ok=True)
        torch.save({"last_source_id": last_source_id, "epochs": epochs,
                    "state": model.state_dict(), "seed": seed}, checkpoint)
    model.eval().requires_grad_(False)
    return model


def bank_for_records(records, args, device, mode, seed):
    memory = LearnabilityMemory(args.seq_len, args.pred_len)
    memory.fit(records)
    learned = fit_learnability(records, seed, epochs=10, device=device)
    group = (POLICIES[mode][0] if mode not in NEW_MODES else
             "none" if mode == "A3" else
             "random_reconstruction" if mode == "A4" else "reconstruction")
    memory.to(device)
    memory.set_group(learned, group, seed)
    x = records["x"].float().cpu()
    std = x.var(1, keepdim=True, unbiased=False).add(1e-5).sqrt()
    source_scale = std.clamp_min(learned["history_std_floor"])
    memory.source_residual_modelnorm = (
        (records["target"].float().cpu() - records["a0_pred"].float().cpu()) /
        source_scale
    ).transpose(1, 2).contiguous().to(device)
    memory.future = ((records["target"].float().cpu() - x.mean(1, keepdim=True)) /
                     source_scale).transpose(1, 2).contiguous().to(device)
    memory.typical_future_disagreement = (
        memory.future - memory.future.median(dim=0).values[None]).abs().median().clamp_min(1e-4)
    return memory, learned


def retrieval_for_point(memory, x, ids, mode, args, split, val_start):
    if mode in NEW_MODES:
        return new_mode_retrieval(memory, x, ids, mode, split, val_start,
                                  getattr(args, "learnability_topk", 5))
    group, view, _, _, _ = POLICIES[mode]
    sk = 0 if view in ("rare", "all") else 3
    uk = 5 if view == "all" else 2
    retrieved = memory.retrieve(x, view=view, common_k=sk, rare_k=uk,
                                sample_ids=ids, split=split,
                                val_first_start=val_start)
    return retrieved


def _record_retrieval(retrieved, memory):
    index = retrieved["indices"]
    channel = torch.arange(index.shape[1], device=index.device)[None, :, None]
    raw = memory.source_residual_modelnorm[index, channel] * retrieved["valid"][..., None]
    return {"source_ids": retrieved["source_starts"].cpu(),
            "valid": retrieved["valid"].cpu(),
            "stable": retrieved["is_common"].cpu(),
            "a0_residual": raw.cpu(),
            "source_future": retrieved["future"].cpu(),
            "p_well": retrieved["p_well"].cpu(),
            "source_typical_scale": torch.full((len(index),),
                float(memory.typical_future_disagreement), dtype=torch.float32)}


@torch.no_grad()
def _causal_mismatched_future(memory, retrieved, ids, split, val_start):
    """Break history/future pairs without introducing not-yet-observed labels.

    Rotating within the selected Top-K would leave median/MAD unchanged, so
    each selected index is instead mapped to a different member of the full
    eligible TRAIN pool for that query. It stays deterministic and per-channel.
    """
    index = retrieved["indices"].cpu()
    valid = retrieved["valid"].cpu()
    ends = memory.ends.cpu()
    mapped = torch.zeros_like(index)
    for bi in range(len(index)):
        if split == "train":
            eligible = (ends <= int(ids[bi])).nonzero(as_tuple=True)[0]
        elif split == "val":
            eligible = (ends <= int(val_start)).nonzero(as_tuple=True)[0]
        else:
            eligible = torch.arange(len(ends))
        if len(eligible) < 2:
            continue
        shift = max(1, len(eligible) // 2)
        for ci in range(index.shape[1]):
            for ki in range(index.shape[2]):
                if not bool(valid[bi, ci, ki]):
                    continue
                position = torch.searchsorted(eligible, index[bi, ci, ki])
                mapped[bi, ci, ki] = eligible[(position + shift) % len(eligible)]
    device = retrieved["future"].device
    channel = torch.arange(index.shape[1], device=device)[None, :, None]
    output = memory.future.to(device)[mapped.to(device), channel]
    return (output * valid.to(device)[..., None]).cpu()


@torch.no_grad()
def collect_fold(model, memory, learned, records, loader, args, device,
                 mode, config, max_batches=0):
    collection = {k: [] for k in ("hidden", "prediction", "target", "scale",
                                   "ids", "source_ids", "valid", "stable", "a0_residual",
                                   "source_future", "p_well", "source_typical_scale",
                                   "random_source_future", "random_valid",
                                   "shuffled_source_future")}
    for batch_index, (x, y, ids, cycle) in enumerate(loader):
        if max_batches and batch_index >= max_batches:
            break
        x = x.float().to(device)
        cycle = cycle.to(device)
        group = (POLICIES[mode][0] if mode not in NEW_MODES else
                 "none" if mode == "A3" else "reconstruction")
        memory.set_group(learned, group, config["seed"])
        prediction, _, _ = run_batch(model, memory, records, mode, config,
                                     x, ids, cycle, "train", None)
        hidden, _, scale = model.encode(x, cycle)
        retrieved = retrieval_for_point(memory, x, ids, mode, args, "train", None)
        source = _record_retrieval(retrieved, memory)
        if mode in NEW_MODES:
            random_retrieval = memory.retrieve(x, view="random",
                common_k=args.learnability_topk, rare_k=0,
                sample_ids=ids, split="train")
            source["random_source_future"] = random_retrieval["future"].cpu()
            source["random_valid"] = random_retrieval["valid"].cpu()
            source["shuffled_source_future"] = _causal_mismatched_future(
                memory, retrieved, ids, "train", None)
        else:
            source["random_source_future"] = torch.zeros_like(source["source_future"])
            source["random_valid"] = source["valid"].clone()
            source["shuffled_source_future"] = torch.zeros_like(source["source_future"])
        for key, value in {
            "hidden": hidden.cpu(), "prediction": prediction.cpu(),
            "target": y[:, -args.pred_len:].float().cpu(),
            "scale": scale.cpu(), "ids": ids.cpu(), **source,
        }.items():
            collection[key].append(value)
    if not collection["ids"]:
        raise RuntimeError("empty chronological OOF fold")
    return {key: torch.cat(items) for key, items in collection.items()}


def _oof_residual_map(folds, args, floor):
    values = {}
    for fold in folds:
        std = fold["scale"].clamp_min(floor)
        residual = ((fold["target"] - fold["prediction"]) / std).transpose(1, 2)
        for i, sample_id in enumerate(fold["ids"].tolist()):
            values[int(sample_id)] = residual[i]
    return values


def add_features(record, residual_map, mode="U4", train_query=False,
                 seq_len=96, pred_len=720):
    ids = record["source_ids"]
    b, c, k = ids.shape
    horizon = record["target"].shape[1]
    oof = torch.zeros(b, c, k, horizon)
    valid = record["valid"].clone()
    for bi in range(b):
        for ci in range(c):
            for ki in range(k):
                row = residual_map.get(int(ids[bi, ci, ki]))
                if row is None:
                    valid[bi, ci, ki] = False
                else:
                    oof[bi, ci, ki] = row[ci]
    if mode == "U8":
        sources = sorted(residual_map)
        for bi in range(b):
            query_start = int(record["ids"][bi])
            candidates = ([source for source in sources
                           if source + seq_len + pred_len <= query_start]
                          if train_query else sources)
            for ci in range(c):
                for ki in range(k):
                    if not candidates:
                        valid[bi, ci, ki] = False
                        oof[bi, ci, ki] = 0
                        continue
                    hashed = (query_start * 1103515245 + ci * 7919 + ki * 12345 + 2021)
                    chosen = candidates[hashed % len(candidates)]
                    oof[bi, ci, ki] = residual_map[chosen][ci]
                    valid[bi, ci, ki] = True
    if mode == "U1":
        oof = record["a0_residual"].clone()
        valid = record["valid"].clone()
    if mode == "U7" and k > 1:
        oof = oof.roll(1, dims=2)
    features = residual_difference_features(oof, valid, record["stable"])
    return select_features(features, mode), float(valid.float().mean())


def add_consensus_features(record, residual_map, mode, train_query=False,
                           seq_len=96, pred_len=720):
    """Concatenate existing OOF dynamics and retrieved-future disagreement.

    Every future is from an already completed TRAIN memory entry. The current
    target field is used by training_loss only, never by this feature builder.
    """
    if mode not in {f"C{i}" for i in range(8)}:
        raise ValueError(mode)
    oof, fraction = add_features(record, residual_map, "U5", train_query,
                                  seq_len, pred_len)
    future = record["source_future"].clone()
    valid = record["valid"].clone()
    if mode == "C6":
        future = record["shuffled_source_future"]
    elif mode == "C7":
        future = record["random_source_future"]
        valid = record["random_valid"]
    typical = record["source_typical_scale"].float().median().clamp_min(1e-4)
    difference = future_difference_features(future, valid, typical,
                                             record["p_well"] if mode != "C7" else None)
    if mode in ("C0", "C4"):
        difference = torch.zeros_like(difference)
    elif mode == "C1":
        difference[..., 1:] = 0
    elif mode == "C2":
        difference[..., 2:] = 0
    return torch.cat((oof, difference), -1), fraction


def create_oof(cli, args, device, datasets, selected, config, output, ref_hash):
    dataset = datasets["train"]
    n = len(dataset)
    starts = (.2, .4, .6, .8)
    folds = []
    fold_audit = []
    for fold, fraction in enumerate(starts):
        lo = int(n * fraction)
        hi = int(n * (fraction + .2)) if fold < 3 else n
        lo = math.ceil(lo / args.seq_len) * args.seq_len
        source_limit = lo - args.seq_len - args.pred_len
        if source_limit < args.seq_len:
            raise RuntimeError("chronological OOF source too small")
        cache = output / f"oof_fold_{fold}.pt"
        if cache.exists():
            saved = torch.load(cache, map_location="cpu", weights_only=False)
            if (saved["reference_sha256"] != ref_hash or
                    saved["source_limit"] != source_limit or
                    saved["fold_reference_epochs"] != cli.oof_reference_epochs or
                    saved["point_mode"] != selected["selected_mode"]):
                raise ValueError("OOF cache configuration mismatch")
            folds.append(saved["record"])
            fold_audit.append(saved["audit"])
            print(json.dumps({"oof_fold": fold, "reused": True}), flush=True)
            continue
        fold_model = train_fold_reference(
            args, dataset, device, cli.seed, source_limit,
            cli.oof_reference_epochs, output / f"fold_A0_{fold}.pt",
            cli.max_batches)
        source_subset = Subset(dataset, list(range(source_limit + 1)))
        source_records = anchor_records(fold_model, source_subset, args, device)
        memory, fitted = bank_for_records(source_records, args, device,
                                          selected["selected_mode"], cli.seed)
        fold_config = {"learnability": fitted, "seed": cli.seed,
                       "lambda_ridge": config["lambda_ridge"],
                       "lambda_stable": config["lambda_stable"]}
        heldout = ordered_loader(dataset, args, range(lo, hi, args.seq_len))
        record = collect_fold(fold_model, memory, fitted, source_records, heldout,
                              args, device, selected["selected_mode"],
                              fold_config, cli.max_batches)
        audit = {"fold": fold, "source_last_start": source_limit,
                 "source_last_complete_end": source_limit + args.seq_len + args.pred_len,
                 "holdout_first_start": lo, "holdout_last_start": hi - 1,
                 "fold_reference_from_scratch": True,
                 "reference_epochs": cli.oof_reference_epochs,
                 "fold_a0_is_full_train_checkpoint": False,
                 "sample_count": len(record["ids"]),
                 "fold_test_mse": float((record["prediction"] - record["target"]).square().mean())}
        if audit["source_last_complete_end"] > lo:
            raise RuntimeError("fold source future overlaps holdout history")
        torch.save({"reference_sha256": ref_hash, "source_limit": source_limit,
                    "fold_reference_epochs": cli.oof_reference_epochs,
                    "point_mode": selected["selected_mode"],
                    "record": record, "audit": audit}, cache)
        folds.append(record)
        fold_audit.append(audit)
        write_json(output / "oof_progress.json", fold_audit)
    return folds, fold_audit


