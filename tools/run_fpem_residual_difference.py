def _build_condition(future_model, bank, record, device):
    hidden = record["hidden"].to(device)
    y_inv = record["prediction"].to(device)
    scale = record["scale"].to(device)
    future = future_model.encode_future(hidden)[0]
    condition = bank.condition(future, y_inv, scale)
    return condition, future, y_inv, scale


def _slices(length, batch_size, seed=None):
    if seed is None:
        indices = torch.arange(length)
    else:
        indices = torch.randperm(length, generator=torch.Generator().manual_seed(seed))
    return indices.split(batch_size)


def _subset(record, ids):
    return {key: value[ids] for key, value in record.items()
            if isinstance(value, torch.Tensor) and len(value) == len(record["ids"])}


def train_original_flow(cli, args, device, oof, out, ref_hash):
    checkpoint = out / "U0_baseline_flow.pt"
    future = HorizonFutureVariant(args.d_model, args.pred_len,
                                  future_patch_len=16, environment_count=0).to(device)
    bank = ProbabilityHeadBank(args.d_model, args.pred_len, patch_len=16,
                               heads=("residual_flow",)).to(device)
    if checkpoint.exists():
        saved = torch.load(checkpoint, map_location=device, weights_only=False)
        if saved["reference_sha256"] != ref_hash:
            raise ValueError("Flow checkpoint/A0 mismatch")
        future.load_state_dict(saved["future"])
        bank.load_state_dict(saved["bank"])
    else:
        params = list(future.horizon_encoder.parameters()) + list(future.future_var_net.parameters())
        params += list(bank.parameters())
        optimizer = torch.optim.Adam(params, lr=1e-4)
        for epoch in range(cli.flow_epochs):
            future.train(); bank.train()
            total = count = 0.
            for batch_number, ids in enumerate(_slices(len(oof["ids"]),
                                                        min(args.batch_size, 16),
                                                        cli.seed + epoch)):
                if cli.max_batches and batch_number >= cli.max_batches:
                    break
                batch = _subset(oof, ids)
                condition, _, y_inv, scale = _build_condition(future, bank, batch, device)
                target = batch["target"].to(device)
                loss, _ = bank.heads["residual_flow"].training_loss(
                    condition, y_inv.detach(), target, scale.detach())
                if not torch.isfinite(loss):
                    raise FloatingPointError("original residual Flow loss non-finite")
                optimizer.zero_grad(set_to_none=True)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(params, 5.)
                optimizer.step()
                total += float(loss.detach())
                count += 1
            print(json.dumps({"original_flow_epoch": epoch + 1,
                              "train_loss": total / max(1, count)}), flush=True)
        torch.save({"reference_sha256": ref_hash,
                    "future": future.state_dict(), "bank": bank.state_dict(),
                    "oof_source": "fresh prefix-trained A0 + full local adaptation"}, checkpoint)
    future.eval().requires_grad_(False)
    bank.eval().requires_grad_(False)
    return future, bank


def train_condition_adapter(cli, args, device, oof, future, bank, mode,
                            out, ref_hash):
    style = "output_scale" if mode == "U6" else "film"
    adapter = ResidualDifferenceCondition(
        14 if mode.startswith("C") else 7, args.d_model, 16, style).to(device)
    checkpoint = out / f"{mode}_adapter.pt"
    if checkpoint.exists():
        saved = torch.load(checkpoint, map_location=device, weights_only=False)
        if saved["reference_sha256"] != ref_hash or saved["mode"] != mode:
            raise ValueError("conditional adapter checkpoint mismatch")
        adapter.load_state_dict(saved["state"])
        return adapter.eval(), saved["history"]
    optimizer = torch.optim.Adam(adapter.parameters(), lr=1e-3)
    history = []
    for epoch in range(cli.adapter_epochs):
        adapter.train()
        total = batches = 0.
        for batch_number, ids in enumerate(_slices(len(oof["ids"]),
                                                    min(args.batch_size, 16),
                                                    cli.seed + 4901 + epoch)):
            if cli.max_batches and batch_number >= cli.max_batches:
                break
            record = _subset(oof, ids)
            with torch.no_grad():
                condition, _, point, scale = _build_condition(future, bank, record, device)
            features = record[f"features_{mode}"].to(device)
            true = record["target"].to(device)
            if style == "film":
                modified = adapter(condition, features)
                loss, _ = bank.heads["residual_flow"].training_loss(
                    modified, point, true, scale)
            else:
                with torch.no_grad():
                    generator = torch.Generator(device=device).manual_seed(
                        cli.seed + 100003 * epoch + batch_number)
                    paths = bank.sample_head("residual_flow", condition, None,
                        point, scale, 8, generator, chunk_size=4,
                        steps=cli.flow_steps)["y_samples"]
                    baseline_sigma = paths.std(1, unbiased=False).clamp_min(.01)
                correction = adapter.scale_correction(features).permute(0, 2, 1)
                sigma = baseline_sigma * correction
                loss = (sigma.log() + .5 * ((true - point) / sigma).square()).mean()
            if not torch.isfinite(loss):
                raise FloatingPointError(f"{mode} loss non-finite")
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(adapter.parameters(), 5.)
            optimizer.step()
            total += float(loss.detach())
            batches += 1
        history.append({"epoch": epoch + 1, "training_loss": total / max(batches, 1)})
        print(json.dumps({"mode": mode, **history[-1]}), flush=True)
    adapter.eval()
    torch.save({"reference_sha256": ref_hash, "mode": mode,
                "state": adapter.state_dict(), "history": history}, checkpoint)
    return adapter, history


@torch.no_grad()
def generate(cli, args, device, record, future, bank, mode, adapter,
             sample_count, seed, collect_paths=False):
    totals = {}
    count = 0
    saved_lower = []; saved_upper = []; saved_true = []
    for batch_number, ids in enumerate(_slices(len(record["ids"]),
                                                min(args.batch_size, 8))):
        if cli.max_batches and batch_number >= cli.max_batches:
            break
        batch = _subset(record, ids)
        condition, _, point, scale = _build_condition(future, bank, batch, device)
        features = batch.get(f"features_{mode}")
        if mode not in ("U0", "C0") and adapter.mode == "film":
            condition = adapter(condition, features.to(device))
        generator = torch.Generator(device=device).manual_seed(seed + batch_number * 1009)
        paths = bank.sample_head("residual_flow", condition, None, point, scale,
                                 sample_count, generator, chunk_size=min(5, sample_count),
                                 steps=cli.flow_steps)["y_samples"]
        if mode == "U6":
            correction = adapter.scale_correction(features.to(device)).permute(0, 2, 1)
            paths = point[:, None] + correction[:, None] * (paths - point[:, None])
        truth = batch["target"].to(device)
        metrics = probabilistic_metrics(paths, truth, point)
        for name in ("CRPS", "PICP_95", "MPIW_95", "WIS",
                     "inv_MSE", "inv_MAE", "mean_MSE", "mean_MAE"):
            totals[name] = totals.get(name, 0.) + float(metrics[name]) * len(ids)
        if collect_paths:
            saved_lower.append(torch.quantile(paths, .025, dim=1).cpu())
            saved_upper.append(torch.quantile(paths, .975, dim=1).cpu())
            saved_true.append(truth.cpu())
        count += len(ids)
    if not count:
        raise RuntimeError("probability evaluation set empty")
    summary = {name: value / count for name, value in totals.items()}
    if collect_paths:
        summary["lower"] = torch.cat(saved_lower)
        summary["upper"] = torch.cat(saved_upper)
        summary["truth"] = torch.cat(saved_true)
    return summary


def _conformal(cal, test, alpha=.05):
    lower, upper, true = cal["lower"], cal["upper"], cal["truth"]
    half = ((upper - lower) / 2).clamp_min(1e-4)
    error = torch.maximum(lower - true, true - upper).clamp_min(0) / half
    per_sample = error.flatten(1).max(-1).values
    rank = min(len(per_sample), math.ceil((len(per_sample) + 1) * (1 - alpha)))
    q = float(per_sample.kthvalue(rank).values)
    half_test = ((test["upper"] - test["lower"]) / 2).clamp_min(1e-4)
    adjusted_lower = test["lower"] - q * half_test
    adjusted_upper = test["upper"] + q * half_test
    y = test["truth"]
    coverage = (adjusted_lower <= y) & (y <= adjusted_upper)
    trajectory = coverage.flatten(1).all(-1).float().mean()
    width = adjusted_upper - adjusted_lower
    interval = width + 40 * (adjusted_lower - y).clamp_min(0) + 40 * (y - adjusted_upper).clamp_min(0)
    return {"calibration_q": q,
            "PICP95_marginal": float(coverage.float().mean()),
            "PICP95_trajectory": float(trajectory),
            "MPIW95": float(width.mean()),
            "interval_score95": float(interval.mean()),
            "calibration_count": len(cal["truth"])}


def main():
    cli = arguments()
    torch.set_num_threads(min(4, torch.get_num_threads()))
    out = ROOT / cli.output / cli.case
    out.mkdir(parents=True, exist_ok=True)
    if (out / "probability_pilot_complete").exists():
        print("probability pilot already complete", flush=True)
        return
    point_dir = ROOT / cli.point_root / cli.case
    selected = json.loads((point_dir / "point_selection.json").read_text(encoding="utf-8"))
    if selected["selected_mode"] in {"P4", "P7", "P8", "A4", "B6", "B7"}:
        raise ValueError("negative control/A0 cannot define final point model")
    point_result = json.loads((point_dir / f"{selected['selected_mode']}_result.json").read_text(encoding="utf-8"))
    cli.protocol = selected.get("protocol", cli.protocol)
    cli.base_run_config = str(BASE / (f"{cli.case}_A0_complementary_gate_predictive_"
                                 "sub0_orth0_refnone_fp0_rank8_bias-4/run_config.json"))
    if cli.case.startswith("moderntcn"):
        cli.allow_legacy_reference_signature = True
    args, model, loaders, device, ref_hash = load_experiment(cli)
    if selected["reference_sha256"] != ref_hash:
        raise ValueError("point/Flow full-A0 checkpoint mismatch")
    full_cache = torch.load(point_dir / "learnability.pt", map_location="cpu", weights_only=False)
    if full_cache["reference_sha256"] != ref_hash:
        raise ValueError("full point-memory reference mismatch")
    full_records = torch.load(
        ROOT / "results/fpem_predictive_memory/pilot_20261024" / cli.case / "phase0_cache.pt",
        map_location="cpu", weights_only=False)["records"]
    memory = LearnabilityMemory(args.seq_len, args.pred_len)
    for name, value in full_cache["bank"].items():
        setattr(memory, name, value.clone())
    memory = memory.to(device)
    learned = full_cache["learnability"]
    selected_mode = selected["selected_mode"]
    group = (POLICIES[selected_mode][0] if selected_mode not in NEW_MODES else
             "none" if selected_mode == "A3" else "reconstruction")
    memory.set_group(learned, group, cli.seed)
    args.learnability_topk = int(point_result.get("topk", 5))
    x = full_records["x"].float()
    std = x.var(1, keepdim=True, unbiased=False).add(1e-5).sqrt()
    source_scale = std.clamp_min(learned["history_std_floor"])
    memory.source_residual_modelnorm = (
        (full_records["target"].float() - full_records["a0_pred"].float()) /
        source_scale
    ).transpose(1, 2).contiguous().to(device)
    memory.future = ((full_records["target"].float() - x.mean(1, keepdim=True)) /
                     source_scale).transpose(1, 2).contiguous().to(device)
    memory.typical_future_disagreement = (
        memory.future - memory.future.median(dim=0).values[None]).abs().median().clamp_min(1e-4)
    config = {"learnability": learned, "seed": cli.seed,
              "lambda_ridge": point_result["ridge"],
              "lambda_stable": point_result["stable_weight"],
              "lambda_huber": point_result.get("lambda_huber", 1.),
              "huber_delta": point_result.get("huber_delta", 1.),
              "topk": args.learnability_topk}
    folds, fold_audit = create_oof(cli, args, device,
                                    {"train": loaders["train"].dataset.dataset},
                                    selected, config, out, ref_hash)
    residual_map = _oof_residual_map(folds, args, learned["history_std_floor"])
    oof = {key: torch.cat([fold[key] for fold in folds]) for key in folds[0]}
    val_data = loaders["val"].dataset.dataset
    half = len(val_data) // 2
    val_start = len(loaders["train"].dataset.dataset.data_x) - args.seq_len
    validation = collect_final(model, memory, learned, full_records,
        ordered_loader(val_data, args, range(0, half)), args, device,
        selected["selected_mode"], config, "val", val_start, cli.max_batches)
    calibration = collect_final(model, memory, learned, full_records,
        ordered_loader(val_data, args, range(half, len(val_data))), args, device,
        selected["selected_mode"], config, "val", val_start, cli.max_batches)
    test = collect_final(model, memory, learned, full_records, loaders["test"],
        args, device, selected["selected_mode"], config, "test", val_start,
        cli.max_batches)
